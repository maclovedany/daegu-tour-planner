def _읽기(파일):
    with (자료 / 파일).open(encoding='utf-8-sig', newline='') as f:
        return list(csv.DictReader(f))


def _수(값):
    try:
        return float(str(값).replace(',', ''))
    except ValueError:
        return None


def _천(값):
    수 = _수(값)
    return f'{int(수):,}' if 수 is not None and 수 == int(수) else str(값)


def _범위(ids):
    """R08, R09, R10 → 'R08~R10'. 앱의 경고 읽기가 범위를 다시 펼친다."""
    수 = sorted({int(i[1:]) for i in ids})
    묶음, 시작 = [], None
    for n, 다음 in zip(수, 수[1:] + [None]):
        시작 = n if 시작 is None else 시작
        if 다음 != n + 1:
            묶음.append(f'R{시작:02d}' if 시작 == n else f'R{시작:02d}~R{n:02d}')
            시작 = None
    return ' · '.join(묶음)


class 근거모음:
    def __init__(self):
        self.행 = []
        self.경고 = {}      # 열쇠 → {종류, 문구, 행}
        self.알림, self.미확인, self.자료목록 = [], [], []

    def 넣기(self, 항목, 이름, 수치, 위치, 출처, 연도, 표본, 한계, 경고=()):
        행 = {'ID': f'R{len(self.행) + 1:02d}', '항목': 항목, '원자료 항목명': 이름, '수치': 수치, '파일 · 행 위치': 위치,
             '출처': 출처, '연도': str(연도), '표본 · 대상': 표본, '한계': 한계 or '—', '경고': ''}
        self.행.append(행)
        for 열쇠 in 경고:
            self.경고[열쇠]['행'].append(행['ID'])
        return 행

    def 경고_정의(self, 열쇠, 종류, 문구):
        self.경고.setdefault(열쇠, {'종류': 종류, '문구': 문구, '행': []})
        return 열쇠

    def 경고목록(self):
        """실제로 행에 걸린 경고만 W1 … 로 번호를 매기고, 행의 '경고' 칸을 채운다."""
        결과 = []
        for w in self.경고.values():
            if not w['행']:
                continue
            wid = f'W{len(결과) + 1}'
            결과.append({'경고ID': wid, '종류': w['종류'], '문구': w['문구'], '적용근거ID': list(w['행'])})
            for 행 in self.행:
                if 행['ID'] in w['행']:
                    행['경고'] = (행['경고'] + ' ' + wid).strip()
        for 행 in self.행:
            행['경고'] = 행['경고'] or '—'
        return 결과


