def _변동(m, 대상, 연속, 단위, 출처):
    """같은 조건의 연도별 값 중 큰 값이 작은 값의 2배 이상이면 '변동 큼' (시험값)."""
    값 = [(해, 수, rid) for 해, 수, rid in 연속 if 수]
    if len(값) < 2:
        return
    작, 큰 = min(값, key=lambda x: x[1]), max(값, key=lambda x: x[1])
    if 큰[1] >= 작[1] * 2:
        표시 = lambda 수: f'{int(수):,}' if 단위 == '명' else f'{수:g}'  # noqa: E731
        열쇠 = m.경고_정의(f'변동:{대상}', '변동 큼', f'{대상} 값은 {작[0]} {표시(작[1])}{단위} ~ {큰[0]} {표시(큰[1])}{단위}으로 해마다 다릅니다 ({출처}, 기준값 시험값: 2배 이상).')
        m.경고[열쇠]['행'].extend(rid for _, _, rid in 값)


def 근거표_글(행들):
    줄 = ['| ' + ' | '.join(열이름) + ' |', '|' + '---|' * len(열이름)]
    줄 += ['| ' + ' | '.join(str(행[열]).replace('|', '／').replace('\n', ' ') for 열 in 열이름) + ' |' for 행 in 행들]
    return '\n'.join(줄)


