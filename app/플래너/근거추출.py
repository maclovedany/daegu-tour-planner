    for 파일, 열, 이름 in [('kosis_foreign_purpose_2024.csv', 'purpose', '방문 목적'), ('kosis_foreign_companion_2024.csv', 'companion', '동반자 유형')]:
        표 = sorted(_읽기(파일), key=lambda r: -_수(r['pct']))[:3]
        m.자료목록.append((f'KOSIS 2024 외국인 {이름}', 파일, '값이 큰 3행', '구분 없음 (전체 값만)'))
