          + '조건: ' + json.dumps(입력3['조건'], ensure_ascii=False) + f"\n확정 체류 기간: {입력3['확정체류기간']}\n"
          + '코스작성조건 (담당자 선택): ' + json.dumps({k: v for k, v in 입력3['코스작성조건'].items() if k != '결정기록'}, ensure_ascii=False)
