    새경고 = [w for w in 코스.get('남은경고', []) if isinstance(w, dict) and not str(w.get('경고ID', '')).startswith('W')]
    코스['남은경고'] = [{'경고ID': w['경고ID'], '적용근거ID': w['적용근거ID'], '문구': w['문구']} for w in 입력3['경고목록']] + 새경고
