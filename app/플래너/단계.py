def 코스용_근거(근거목록):
    """코스 짜기에 넘길 근거만 고른다. 조건이 많으면 근거가 600행을 넘어 입력이 길어지고 1분 안에 끝나지 않는다.
    관심 관광지는 최근 두 해에서 많이 나온 60곳, 연도별 수 · 비율은 최근 두 해만 넘긴다. 저장되는 근거표는 줄이지 않는다."""
    해 = sorted({x.get('연도', '')[:4] for x in 근거목록 if x.get('연도', '')[:4].isdigit()})[-2:]
    관심 = [x for x in 근거목록 if x.get('원자료항목명', '').startswith('관심 관광지') and x.get('연도', '')[:4] in 해]
    관심.sort(key=lambda x: (-int(x.get('연도', '0')[:4]), -(x.get('수치') if isinstance(x.get('수치'), (int, float)) else 0)))
    고른 = {x['근거ID'] for x in 관심[:60]}
    연도별 = ('외국인 방문자 수', '외국인 방문자 거주 국가', '중구 거주 국가', '향촌문화관')
    결과 = []
    for x in 근거목록:
        이름 = x.get('원자료항목명', '')
        if 이름.startswith('관심 관광지'):
            if x['근거ID'] in 고른:
                결과.append(x)
        elif any(k in 이름 for k in 연도별):
            if x.get('연도', '')[:4] in 해 or '합계' in 이름:
                결과.append(x)
        else:
            결과.append(x)
    return 결과


