# ───────────── 1단계: 자료 확인 (코드만) ─────────────
def 자료_확인(조건):
    근거 = 추출(조건)
    표 = '\n'.join(f'| {a} | `{b}` | {c} | {d} |' for a, b, c, d in 근거['자료목록'])
    글 = (f"## 조건 요약\n- 방문객: 외국인\n- 시기: {조건['계절']} ({' · '.join(map(str, 계절_월[조건['계절']]))}월)\n- 대상 언어권: {' · '.join(조건['언어권'])}\n"
         f"- 지역: {' · '.join(조건['지역'])}\n- 체류 기간: {조건['체류기간']}\n\n## 볼 수 있는 자료\n| 자료 | 파일 | 고른 행 | 재는 방식 |\n|---|---|---|---|\n{표}\n\n"
         f"## 알림 (E1)\n" + ('\n'.join('- ' + a for a in 근거['알림']) or '없음') + '\n\n(이 결과는 앱이 자료 고르기 규칙대로 만든 것이며 AI를 부르지 않았습니다.)\n')
    return 근거, 글


# ───────────── 2단계: 수요 분석 (요약과 해석만 AI) ─────────────
def _근거_줄(행들):
    return '\n'.join(f"{x['ID']}|{x['항목']}|{x['원자료 항목명']}|{x['수치']}|{x['출처']} {x['연도']}|{x['표본 · 대상']}|{x['경고']}" for x in 행들)


def 수요_글(근거, 요약, 해석):
    """2단계 결과 글 (기존 형식). 근거표와 경고는 코드가 만든 것을 그대로 싣는다."""
    return ('## 수요 분석 요약\n' + '\n'.join(f"- {s.get('항목', '')}: {s['문장']} [{' · '.join(s.get('근거', []))}]" for s in 요약)
            + f"\n해석: {해석}\n\n## 근거표\n{근거표_글(근거['행'])}\n\n## 경고 (E3)\n{경고_글(근거['경고'])}\n\n## 미확인사항\n"
            + ('\n'.join('- ' + m for m in 근거['미확인']) or '- 없음') + '\n- 기관 데이터 없음\n\n## 담당자 선택 (E3)\n- 미선택\n')


async def 수요_분석(조건, 근거, 지시=''):
    시스템 = (
        '너는 2단계 수요 근거 에이전트다. 근거표와 경고는 앱이 원자료에서 이미 만들었다. 너는 그 표만 보고 "수요 분석 요약"과 "해석"을 쓴다. '
        '표에 없는 수치를 쓰지 않고, 한 문장에는 한 자료만 쓴다. 아래 지침의 요약 · 수치 쓰는 법을 따른다. 근거표나 경고를 다시 쓰지 않는다.\n'
        '출력은 JSON 객체 하나만: {"요약":[{"항목":"방문객|좋았던 점|음식|숙박|보조","문장":"출처 · 연도 · 표본이 붙은 한 문장","근거":["R.."]}],'
        '"해석":"수요의 세기와 근거의 강약만 2~3문장"}. 요약은 항목당 1~2문장, 모두 합쳐 10문장 이하.\n\n'
        + 지침('지침/2_수요근거/역할.md', '지침/2_수요근거/근거표.md', '지침/2_수요근거/출력.md', '지침/2_수요근거/추천.md'))
    입력 = ('조건: ' + json.dumps(조건, ensure_ascii=False) + (f'\n\n고쳐야 할 점 (총괄 에이전트 지시): {지시}' if 지시 else '')
          + '\n\n경고:\n' + '\n'.join(f"{w['경고ID']} {w['종류']}: {w['문구']}" for w in 근거['경고'])
          + '\n\n근거표 (ID|항목|원자료 항목명|수치|출처 연도|표본|경고):\n' + _근거_줄(근거['행']))
    답, 초 = await 부르기(시스템, 입력)
    값 = JSON_꺼내기(답)
    요약 = [s for s in 값.get('요약', []) if isinstance(s, dict) and s.get('문장')]
    있는 = {x['ID']: x for x in 근거['행']}
    문제 = []
    for s in 요약:   # 요약에 쓴 숫자가 가리킨 근거 행에 실제로 있는지 대조한다
        근거글 = ' '.join(있는[r]['수치'] + ' ' + 있는[r]['표본 · 대상'] + ' ' + 있는[r]['연도'] for r in s.get('근거', []) if r in 있는)
        없는 = [r for r in s.get('근거', []) if r not in 있는]
        if 없는:
            문제.append(f"근거표에 없는 ID를 가리킴: {', '.join(없는)}")
        for 수 in re.findall(r'\d[\d,]*\.\d+%|\d{1,3}(?:,\d{3})+명', s['문장']):
            if 수.rstrip('%명') not in 근거글:
                문제.append(f"요약의 {수}가 가리킨 근거 행에 없음: {s['문장'][:40]}…")
    글 = 수요_글(근거, 요약, 값.get('해석', ''))
    return {'글': 글, '요약': 요약, '해석': 값.get('해석', ''), '문제': 문제, '초': 초}


